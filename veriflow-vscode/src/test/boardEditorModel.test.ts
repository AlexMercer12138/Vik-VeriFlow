import assert from 'node:assert/strict';
import { inspectBoardDraft, parseBoardDraft, emptyBoard } from '../archDesign/boardEditorModel';
const draft = emptyBoard();
draft.id = 'uart';
draft.name = 'UART';
draft.model.pins = {A1:'set_property PACKAGE_PIN A1 [get_ports {signal name}]\n'};
draft.model.interfaces = [{ id: 'UART0', signals: [{ id: 'tx', direction: 'output', pins: ['A1'] }] }];
assert.deepEqual(inspectBoardDraft(draft).issues, []);
const invalid = structuredClone(draft);
invalid.model.interfaces[0].signals[0].pins = ['missing'];
assert.match(inspectBoardDraft(invalid).issues.map(i => i.message).join(' '), /Select each pin/);
assert.deepEqual(parseBoardDraft(draft), draft);
console.log('Minimal board drafts validate local interfaces and pin mappings');
